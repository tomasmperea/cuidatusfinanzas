// Tema: oscuro por defecto, el switch pasa a claro y queda guardado al recargar.
import { chromium } from 'playwright';
const [base = 'http://localhost:5173/cuidatusfinanzas/'] = process.argv.slice(2);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 }, colorScheme: 'light' });
const fallas = [], errores = [];
p.on('pageerror', (e) => errores.push(e.message));
const ok = (c, m) => { if (!c) fallas.push(m); };
const fondo = () => p.evaluate(() => getComputedStyle(document.body).backgroundColor);
await p.goto(`${base}?fixtures=1#inicio`);
await p.waitForSelector('[data-testid="kpi-liquidez"]');
ok(await fondo() === 'rgb(20, 18, 26)', `por defecto no es oscuro aunque el teléfono esté en claro: ${await fondo()}`);
ok((await p.getAttribute('meta[name="theme-color"]', 'content')) === '#14121A', 'barra del sistema no es oscura');
await p.click('[data-testid="tema"]');
ok(await fondo() === 'rgb(247, 244, 239)', `el switch no pasa a claro: ${await fondo()}`);
ok((await p.getAttribute('[data-testid="tema"]', 'aria-label')) === 'Pasar a tema oscuro', 'etiqueta del botón incorrecta');
await p.reload(); await p.waitForSelector('[data-testid="kpi-liquidez"]');
ok(await fondo() === 'rgb(247, 244, 239)', 'el tema claro no quedó guardado');
const fuente = await p.evaluate(() => getComputedStyle(document.body).fontFamily);
ok(fuente.includes('Plus Jakarta'), `fuente: ${fuente}`);
const externos = [];
p.on('request', (r) => { const u = new URL(r.url()); if (!['localhost', '127.0.0.1'].includes(u.hostname)) externos.push(u.hostname); });
await p.reload(); await p.waitForTimeout(800);
ok(!externos.some((h) => /google|gstatic/.test(h)), `pidió la fuente afuera: ${externos}`);
await p.click('[data-testid="tema"]');
ok(await fondo() === 'rgb(20, 18, 26)', 'no vuelve a oscuro');
await b.close();
if (errores.length) fallas.push(...errores);
console.log(fallas.length ? 'FALLAS:\n- ' + fallas.join('\n- ') : 'tema OK');
process.exit(fallas.length ? 1 : 0);
